using FazFort.Discovery;
using System.Text.Json;
int checks = 0;
void Check(bool value, string message) { if (!value) throw new Exception(message); checks++; }
var now = DateTimeOffset.Parse("2026-11-05T00:00:00Z");
var movie = Guid.NewGuid(); var series = Guid.NewGuid(); var ep = Guid.NewGuid();
var ledger = new Ledger();
ledger.Baseline([new(movie,"Movie",true), new(series,"Series",false),new(ep,"Episode",true,series,2)],now);
Check(ledger.Arrivals.Count == 0,"Baseline must not create recent badges");
Check(!ledger.Observe(new(movie,"Movie",true),now.AddDays(1)),"Repeated add event is ignored");
Check(!ledger.Observe(new(Guid.NewGuid(),"Movie",false),now),"Unplayable movie is ignored");
var newMovie = Guid.NewGuid();ledger.Observe(new(newMovie,"Movie",true),now.AddDays(1));
Check(ledger.Arrivals[newMovie].AddedAt == now.AddDays(1),"Observed time is saved");
ledger.Observe(new(Guid.NewGuid(),"Episode",true,series,2,null,now.AddDays(-60)),now.AddDays(1));
Check(ledger.Arrivals.ContainsKey(series),"Newly added episode on existing series records AddedAt for Recently Added badge");
Check(ledger.Arrivals[series].AddedAt == now.AddDays(1),"Existing series AddedAt tracks latest episode arrival time");
Check(ledger.Arrivals[series].NewEpisodesAt is null,"Old-aired episode creates no New Episodes badge");
ledger.Observe(new(Guid.NewGuid(),"Episode",true,series,3,null,now.AddDays(-5)),now.AddDays(2));
Check(ledger.Arrivals[series].NewEpisodesAt == now.AddDays(-5),"Playable episode aired within 30 days sets NewEpisodesAt");
Check(ledger.Arrivals[series].AddedAt == now.AddDays(2),"Series AddedAt also advances alongside NewEpisodesAt");
ledger.Observe(new(Guid.NewGuid(),"Episode",true,series,3,null,now.AddDays(-1)),now.AddDays(3));
Check(ledger.Arrivals[series].NewEpisodesAt == now.AddDays(-1),"Newer aired playable episode advances NewEpisodesAt");
var newSeries = Guid.NewGuid();ledger.Observe(new(newSeries,"Series",false),now);
Check(!ledger.Arrivals.ContainsKey(newSeries),"Empty new series has no arrival badge");
ledger.Observe(new(Guid.NewGuid(),"Episode",true,newSeries,1,null,now.AddDays(-120)),now.AddHours(1));
Check(ledger.Arrivals[newSeries].AddedAt == now.AddHours(1),"Series is added when playable content arrives");
Check(ledger.Arrivals[newSeries].NewEpisodesAt is null,"Old-aired first season gets no New Episodes badge");
ledger.Observe(new(Guid.NewGuid(),"Episode",false,newSeries,1,null,now.AddDays(-2)),now.AddHours(2));
Check(ledger.Arrivals[newSeries].NewEpisodesAt is null,"Unplayable (undownloaded) recent episode gets no New Episodes badge");
ledger.SyncEpisodePremieres([new(ep,"Episode",true,series,2,null,now.AddDays(-45))],now.AddDays(3));
Check(ledger.Arrivals[series].NewEpisodesAt is null,"Full scan clears NewEpisodesAt once no playable episode aired within 30 days");
var restored=JsonSerializer.Deserialize<Ledger>(JsonSerializer.Serialize(ledger))!;
Check(!restored.Observe(new(newMovie,"Movie",true),now.AddDays(9)),"Restart and rescan preserve de-duplication");
Check(restored.Arrivals[newMovie].AddedAt == now.AddDays(1),"Arrival survives restart");
var root=Path.GetFullPath(Path.Combine(AppContext.BaseDirectory,"../../../../.."));
var defaults=JsonDocument.Parse(File.ReadAllText(Path.Combine(root,"config/default.json"))).RootElement;
Check(ConfigPolicy.Valid(defaults),"Shipped rules pass server validation");
Check(!ConfigPolicy.Valid(JsonDocument.Parse("{\"schemaVersion\":\"1\"}").RootElement),"Malformed schema is rejected without throwing");
Check(!ConfigPolicy.Valid(JsonDocument.Parse("null").RootElement),"Null configuration is rejected");
var altered=System.Text.Json.Nodes.JsonNode.Parse(defaults.GetRawText())!;
altered["pages"]!["home"]!["rules"]![0]!["Types"]=new System.Text.Json.Nodes.JsonArray("Episode");
Check(!ConfigPolicy.Valid(JsonDocument.Parse(altered.ToJsonString()).RootElement),"Invalid media types are rejected by server");
var pendingMovie=Guid.NewGuid();var baseline2=new Ledger();baseline2.Baseline([new(pendingMovie,"Movie",false)],now);
Check(baseline2.Observe(new(pendingMovie,"Movie",true),now.AddDays(1)),"Previously virtual movie earns arrival only once playable");
var html="<html><head></head><body><script src=\"other.js\"></script></body></html>";
var injected=WebMarkup.Inject(html,"0.3.2.0",true);
Check(injected.Contains("../FazFortDiscovery/Assets/discovery.js?v=0.3.2.0"),"Asset respects reverse-proxy base path through relative URL");
Check(WebMarkup.Inject(injected,"0.3.2.0",true)==injected,"Repeated transformations do not duplicate script");
Check(WebMarkup.Inject(injected,"0.3.2.0",false)==html,"Disable removes only owned script");
Check(WebMarkup.Inject(html,"bad\"version",true)==html,"Invalid version cannot inject markup");
Check(WebMarkup.Inject("fragment","0.3.2.0",true)=="fragment","Non-index fragments unchanged");
Check(WebMarkup.Inject("<BODY></BODY>","0.3.2.0",true).Contains("data-discovery-asset"),"Uppercase body closing tag supported");
Check(WebMarkup.Inject(injected,"0.3.3.0",true).Contains("v=0.3.3.0"),"Upgrade replaces old asset URL");
var editorConfig=System.Text.Json.Nodes.JsonNode.Parse(defaults.GetRawText())!;
editorConfig["pages"]!["home"]!["opening"]=new System.Text.Json.Nodes.JsonArray("anchor:MyMedia","rule:popcorn","family:director");
editorConfig["pages"]!["home"]!["layouts"]=new System.Text.Json.Nodes.JsonObject{["rule:popcorn"]="portrait",["anchor:DiscoverMovies"]="portrait"};
Check(ConfigPolicy.Valid(JsonDocument.Parse(editorConfig.ToJsonString()).RootElement),"Visual opening rows and artwork save on the server");
editorConfig["pages"]!["home"]!["opening"]=new System.Text.Json.Nodes.JsonArray("rule:missing");
Check(!ConfigPolicy.Valid(JsonDocument.Parse(editorConfig.ToJsonString()).RootElement),"Unknown pinned category is rejected");
editorConfig["pages"]!["home"]!["opening"]=new System.Text.Json.Nodes.JsonArray("family:director");
editorConfig["pages"]!["home"]!["layouts"]!["rule:popcorn"]="stretch";
Check(!ConfigPolicy.Valid(JsonDocument.Parse(editorConfig.ToJsonString()).RootElement),"Unsupported artwork layouts are rejected");
var remuxedMovie = Guid.NewGuid();
var historicalDate = now.AddDays(-60);
ledger.Observe(new(remuxedMovie, "Movie", true, default, 0, historicalDate), now);
Check(ledger.Arrivals[remuxedMovie].AddedAt == historicalDate, "Historical DateCreated is preserved across remux/rescan instead of minting fake recent arrival");
var ratingsConfig = System.Text.Json.Nodes.JsonNode.Parse(defaults.GetRawText())!;
ratingsConfig["ratings"] = new System.Text.Json.Nodes.JsonObject { ["tomatometer"] = true, ["popcornmeter"] = true, ["stars"] = false };
Check(ConfigPolicy.Valid(JsonDocument.Parse(ratingsConfig.ToJsonString()).RootElement), "Ratings preference object passes server validation");
ratingsConfig["ratings"]!["tomatometer"] = "yes";
Check(!ConfigPolicy.Valid(JsonDocument.Parse(ratingsConfig.ToJsonString()).RootElement), "Non-boolean ratings preference is rejected");
ratingsConfig["ratings"] = new System.Text.Json.Nodes.JsonObject { ["unknown"] = true };
Check(!ConfigPolicy.Valid(JsonDocument.Parse(ratingsConfig.ToJsonString()).RootElement), "Unknown ratings preference key is rejected");

// Oscars Season policy & asset validation tests
var defaultOscars = OscarsPolicy.DefaultConfig();
Check(defaultOscars.Categories.Count == 24, "Default Oscars config includes all 24 official Academy Award categories");
Check(!OscarsPolicy.IsActive(defaultOscars, "America/Los_Angeles", now), "Disabled Oscars config is not active");
defaultOscars.Enabled = true;
Check(OscarsPolicy.IsActive(defaultOscars, "America/Los_Angeles", now), "Enabled Oscars config without date bounds is active immediately");
defaultOscars.StartDate = "2026-01-22";
defaultOscars.EndDate = "2026-03-20";
Check(OscarsPolicy.IsActive(defaultOscars, "America/Los_Angeles", DateTimeOffset.Parse("2026-02-15T18:00:00Z")), "Oscars config is active within start and end dates");
Check(!OscarsPolicy.IsActive(defaultOscars, "America/Los_Angeles", DateTimeOffset.Parse("2026-01-10T18:00:00Z")), "Oscars config is inactive before start date");
Check(!OscarsPolicy.IsActive(defaultOscars, "America/Los_Angeles", DateTimeOffset.Parse("2026-03-25T18:00:00Z")), "Oscars config is inactive after end date");
var validatedOscars = OscarsPolicy.ValidateAndNormalize(defaultOscars);
Check(validatedOscars.Categories.Count == 24 && validatedOscars.NavTitle == "Oscars", "Default Oscars config validates and normalizes cleanly");
defaultOscars.StartDate = "2026-04-01";
try { OscarsPolicy.ValidateAndNormalize(defaultOscars); throw new Exception("Reversed Oscars dates accepted"); } catch (ArgumentException) { checks++; }
var tinyPng = "data:image/png;base64," + Convert.ToBase64String(new byte[] { 0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00 });
var parsedHero = OscarsPolicy.ValidateAsset("hero", tinyPng);
Check(parsedHero.Extension == ".png" && parsedHero.ContentType == "image/png", "Valid PNG asset magic bytes pass");
var safeSvg = "data:image/svg+xml;base64," + Convert.ToBase64String(System.Text.Encoding.UTF8.GetBytes("<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 100 40\"><text>OSCARS</text></svg>"));
Check(OscarsPolicy.ValidateAsset("logo", safeSvg).Extension == ".svg", "Static SVG logo passes validation");
var evilSvg = "data:image/svg+xml;base64," + Convert.ToBase64String(System.Text.Encoding.UTF8.GetBytes("<svg><script>alert(1)</script></svg>"));
try { OscarsPolicy.ValidateAsset("logo", evilSvg); throw new Exception("Scripted SVG accepted"); } catch (ArgumentException) { checks++; }
try { OscarsPolicy.ValidateAsset("hero", safeSvg); throw new Exception("SVG accepted for hero backdrop"); } catch (ArgumentException) { checks++; }

Console.WriteLine($"{checks} native ledger and validation checks passed.");
