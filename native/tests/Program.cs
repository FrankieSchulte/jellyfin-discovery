using FazFort.Discovery;
using System.Text.Json;
int checks = 0;
void Check(bool value, string message) { if (!value) throw new Exception(message); checks++; }
var now = DateTimeOffset.Parse("2026-11-05T00:00:00Z");
var movie = Guid.NewGuid(); var series = Guid.NewGuid(); var ep = Guid.NewGuid();
var ledger = new Ledger();
ledger.Baseline([new(movie,"Movie",true), new(series,"Series",false),new(ep,"Episode",true,series,2)],now);
Check(ledger.Arrivals.Count == 0,"Baseline must not create recent badges");
Check(!ledger.Observe(new(movie,"Movie",true),now.AddDays(1)),"Repeated add event is ignored");
Check(!ledger.Observe(new(Guid.NewGuid(),"Movie",false),now),"Unplayable movie is ignored");
var newMovie = Guid.NewGuid();ledger.Observe(new(newMovie,"Movie",true),now.AddDays(1));
Check(ledger.Arrivals[newMovie].AddedAt == now.AddDays(1),"Observed time is saved");
ledger.Observe(new(Guid.NewGuid(),"Episode",true,series,2),now.AddDays(1));
Check(!ledger.Arrivals.ContainsKey(series),"New episode in existing season creates no New Season badge");
ledger.Observe(new(Guid.NewGuid(),"Episode",true,series,3),now.AddDays(2));
Check(ledger.Arrivals[series].NewSeasonAt == now.AddDays(2),"First playable episode in new season records arrival");
ledger.Observe(new(Guid.NewGuid(),"Episode",true,series,3),now.AddDays(3));
Check(ledger.Arrivals[series].NewSeasonAt == now.AddDays(2),"Later episodes do not reset season arrival");
var newSeries = Guid.NewGuid();ledger.Observe(new(newSeries,"Series",false),now);
Check(!ledger.Arrivals.ContainsKey(newSeries),"Empty new series has no arrival badge");
ledger.Observe(new(Guid.NewGuid(),"Episode",true,newSeries,1),now.AddHours(1));
Check(ledger.Arrivals[newSeries].AddedAt == now.AddHours(1),"Series is added when playable content arrives");
Check(ledger.Arrivals[newSeries].NewSeasonAt is null,"First season is not a new season badge");
ledger.Observe(new(Guid.NewGuid(),"Episode",true,series,0),now);
Check(ledger.Arrivals[series].NewSeasonAt == now.AddDays(2),"Specials do not change season badge");
var restored=JsonSerializer.Deserialize<Ledger>(JsonSerializer.Serialize(ledger))!;
Check(!restored.Observe(new(newMovie,"Movie",true),now.AddDays(9)),"Restart and rescan preserve de-duplication");
Check(restored.Arrivals[newMovie].AddedAt == now.AddDays(1),"Arrival survives restart");
var root=Path.GetFullPath(Path.Combine(AppContext.BaseDirectory,"../../../../.."));
var defaults=JsonDocument.Parse(File.ReadAllText(Path.Combine(root,"config/default.json"))).RootElement;
Check(ConfigPolicy.Valid(defaults),"Shipped rules pass server validation");
Check(!ConfigPolicy.Valid(JsonDocument.Parse("{\"schemaVersion\":\"1\"}").RootElement),"Malformed schema is rejected without throwing");
Check(!ConfigPolicy.Valid(JsonDocument.Parse("null").RootElement),"Null configuration is rejected");
var altered=System.Text.Json.Nodes.JsonNode.Parse(defaults.GetRawText())!;
altered["pages"]!["home"]!["rules"]![0]!["Types"]=new System.Text.Json.Nodes.JsonArray("Episode");
Check(!ConfigPolicy.Valid(JsonDocument.Parse(altered.ToJsonString()).RootElement),"Invalid media types are rejected by server");
var pendingMovie=Guid.NewGuid();var baseline2=new Ledger();baseline2.Baseline([new(pendingMovie,"Movie",false)],now);
Check(baseline2.Observe(new(pendingMovie,"Movie",true),now.AddDays(1)),"Previously virtual movie earns arrival only once playable");
var html="<html><head></head><body><script src=\"other.js\"></script></body></html>";
var injected=WebMarkup.Inject(html,"0.3.2.0",true);
Check(injected.Contains("../FazFortDiscovery/Assets/discovery.js?v=0.3.2.0"),"Asset respects reverse-proxy base path through relative URL");
Check(WebMarkup.Inject(injected,"0.3.2.0",true)==injected,"Repeated transformations do not duplicate script");
Check(WebMarkup.Inject(injected,"0.3.2.0",false)==html,"Disable removes only owned script");
Check(WebMarkup.Inject(html,"bad\"version",true)==html,"Invalid version cannot inject markup");
Check(WebMarkup.Inject("fragment","0.3.2.0",true)=="fragment","Non-index fragments unchanged");
Check(WebMarkup.Inject("<BODY></BODY>","0.3.2.0",true).Contains("data-discovery-asset"),"Uppercase body closing tag supported");
Check(WebMarkup.Inject(injected,"0.3.3.0",true).Contains("v=0.3.3.0"),"Upgrade replaces old asset URL");
Console.WriteLine($"{checks} native ledger and validation checks passed.");
